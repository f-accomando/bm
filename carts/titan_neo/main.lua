Data.CPU = {
  easy = { name = "EASY", think = 22, guard = 0.2, attack = 0.25, chain = 0.2, special = 0.15 },
  normal = { name = "NORMAL", think = 12, guard = 0.5, attack = 0.45, chain = 0.6, special = 0.35 },
