local function step(p, fighters)
  p.t = p.t + 1
  local k = p.kind
  if k == "anim" then
    if p.t < 0 then return true end
    p.x, p.h = p.x + p.vx, p.h + p.vh
    return p.t < #p.names * p.tick
  elseif k == "bullet" then
    return bullet(p, fighters)
  elseif k == "bit" then
    p.x, p.h = p.x + p.vx, p.h + p.vh
    p.vh = p.vh - 0.45
    if p.h < 0 then p.h, p.vh, p.vx = 0, -p.vh * 0.3, p.vx * 0.6 end
    return p.t < p.life
  elseif k == "smoke" then
    p.x, p.h = p.x + p.vx, p.h + 0.9
    p.r = p.r + 0.2
    return p.t < p.life
  elseif k == "trail" then
    -- a robot hit in the middle of the cut loses it
    return p.t < p.life and p.f.state == "attack"
  elseif k == "plate" then
    if p.vh ~= 0 or p.h + p.low > 0 then
      p.x, p.h = p.x + p.vx, p.h + p.vh
      p.vh = p.vh - GRAV
      if p.h + p.low <= 0 then
        p.h = -p.low
        if p.vh < -2.5 then
          p.vh, p.vx = -p.vh * 0.35, p.vx * 0.6
          Fx.dust(p.x)
        else
          p.vh, p.vx = 0, 0
        end
      end
    end
    return p.t < p.life
  end
  return false
end

local function update_list(list, fighters)
  local j = 0
  for i = 1, #list do
    local p = list[i]
    if step(p, fighters) then
      j = j + 1
      list[j] = p
    end
  end
  for i = #list, j + 1, -1 do list[i] = nil end
end

