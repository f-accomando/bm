"""The map tiles of Yharnam 8: the grounds made by rule (seamless 8 x 8),
the rest drawn by hand (hex digits, "." = 0: there the ground under it
shows, the game draws it first). Flags: 0 solid, 1 a light, 2 it glows
(drawn again after the darkness), 3 it needs the ground under it.
"""
import random

SOLID, LIGHT, GLOW, UNDER = 1, 2, 4, 8


def _grid(f):
    return ["".join("%x" % f(x, y) for x in range(8)) for y in range(8)]


def cobble(seed, base=5, hi=13, gap=1):
    """round stones: cells round random points (on a torus), dark between"""
    r = random.Random(seed)
    pts = [(r.uniform(0, 8), r.uniform(0, 8)) for _ in range(5)]

    def near(x, y):
        ds = []
        for k, (px, py) in enumerate(pts):
            dx = min(abs(x - px), 8 - abs(x - px))
            dy = min(abs(y - py), 8 - abs(y - py))
            ds.append((dx * dx + dy * dy, k, dx, dy, px, py))
        ds.sort()
        return ds

    def f(x, y):
        ds = near(x + 0.5, y + 0.5)
        if ds[1][0] ** 0.5 - ds[0][0] ** 0.5 < 0.75:
            return gap
        _, k, dx, dy, px, py = ds[0]
        # lit from above left
        ox = ((x + 0.5 - px + 4) % 8) - 4
        oy = ((y + 0.5 - py + 4) % 8) - 4
        return hi if ox + oy < -1.2 else base
    return _grid(f)


def bricks(seed, w=4, h=2, base=2, hi=5, gap=1):
    """setts: rows of stones, every other row shifted half a stone"""
    r = random.Random(seed)
    shade = {}

    def f(x, y):
        row = y // h
        off = (w // 2) * (row % 2)
        if y % h == h - 1 or (x + off) % w == w - 1:
            return gap
        k = (row, (x + off) // w)
        if k not in shade:
            shade[k] = r.random() < 0.35
        return hi if shade[k] and (y % h == 0) else base
    return _grid(f)


def noise(seed, cols, weights):
    r = random.Random(seed)
    return _grid(lambda x, y: r.choices(cols, weights)[0])


