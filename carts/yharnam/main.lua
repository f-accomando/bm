-- burnt, struck: hurt (three ways), knocked down, or killed
local function hurt(amount, heavy)
  if P.inv > 0 or P.act == "dead" or P.act == "down" or P.act == "lying" or P.act == "getup" then return end
  P.hp = P.hp - amount
  sfx_hurt()
  local now = t
  local recent = 0
  P.hits[#P.hits + 1] = now
  for _, h in ipairs(P.hits) do if now - h < 200 then recent = recent + 1 end end
  if P.hp <= 0 then
    P.hp, P.act, died_t = 0, "dead", 0
    play(xname("death"))
  elseif heavy or recent >= 3 then
    P.hits = {}
    P.act, P.inv = "down", 0
    play(xname("down"))
  else
    P.act, P.inv = "hurt", 50
    play(xname("hurt" .. math.random(3)))
  end
end

