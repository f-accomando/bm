local function play(name, rev)
  local a = HUNT[name]
  P.anim, P.rev, P.ft, P.newf = name, rev or false, 0, true
  P.f = rev and #a.t or 1
end

-- one tick of the animation (rate: ticks per tick); true when a one-shot
-- animation has just ended (it stays on its last frame)
local function step_anim(rate)
  local a = HUNT[P.anim]
  P.newf = false
  P.ft = P.ft + (rate or 1)
  if P.ft >= a.t[P.f] then
    if P.rev then
      if P.f > 1 then P.f, P.ft, P.newf = P.f - 1, 0, true else return true end
    elseif P.f < #a.t then P.f, P.ft, P.newf = P.f + 1, 0, true
    elseif a.loop then P.f, P.ft, P.newf = 1, 0, true
    else return true end                    -- ended: it stays so
  end
  return false
end

local function xname(n) return P.ext and n .. "_x" or n end

-- moves the hunter by (vx, vy), sliding round posts and corners
local function walk_by(vx, vy)
  local nx, ny = P.x + vx, P.y + vy
  local mx, my = false, false
  if not blocked(nx, P.y) then P.x, mx = nx, true end
  if not blocked(P.x, ny) then P.y, my = ny, true end
  local sp = max(abs(vx), abs(vy))
  if vx ~= 0 and not mx and abs(vy) < 0.01 then
    for _, o in ipairs({ -1, 1 }) do
      if not blocked(nx, P.y + o * sp) then P.x, P.y = nx, P.y + o * sp; return end
    end
  elseif vy ~= 0 and not my and abs(vx) < 0.01 then
    for _, o in ipairs({ -1, 1 }) do
      if not blocked(P.x + o * sp, ny) then P.x, P.y = P.x + o * sp, ny; return end
    end
  end
end

local function forward(d)
  local v = DIRV[P.dir + 1]
  walk_by(v[1] * d, v[2] * d)
end

