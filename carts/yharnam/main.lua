  end
  local placed = {}
  for _, p in ipairs(ch.lampspots) do
    local ok = true
    for _, q in ipairs(placed) do
      if abs(q[1] - p[1]) + abs(q[2] - p[2]) < 8 then ok = false end
    end
    if ok then
      placed[#placed + 1] = p
      take(p[1], p[2])
