local function update_play()
  local dx, dy = 0, 0
  if btn(0) then dx = dx - 1 end
  if btn(1) then dx = dx + 1 end
  if btn(2) then dy = dy - 1 end
  if btn(3) then dy = dy + 1 end
  if P.inv > 0 then P.inv = P.inv - 1 end
  if flash > 0 then flash = flash - 1 end
  if tracer then tracer[5] = tracer[5] - 1; if tracer[5] <= 0 then tracer = nil end end
  local pcx, pcy = fdiv(P.x, CPX), fdiv(P.y, CPX)
  -- lamps in reach
  near_lamp = nil
  if not P.act then
    for cy = pcy - 1, pcy + 1 do
      for cx = pcx - 1, pcx + 1 do
        local ch = chunk(cx, cy)
        if ch and ch.ready then
          for _, l in ipairs(ch.lamps) do
            if not lamp_state[l.key] and abs(l.x - P.x) < 22 and abs(l.y - P.y) < 18 then near_lamp = l end
          end
        end
      end
    end
  end

  local act = P.act
  if not act then
    P.moving = dx ~= 0 or dy ~= 0
    if btnp(4) and near_lamp then
      lamp_state[near_lamp.key] = true
      lamps_lit = lamps_lit + 1
      P.spawn = { near_lamp.x, near_lamp.y + 14 }
      sfx_light()
      for k = 1, 24 do
        local a = math.random() * 2 * PI
        spawn(near_lamp.x, near_lamp.y - 66, cos(a) * 0.8, sin(a) * 0.8 - 0.6, 30 + math.random(20), 4)
      end
    elseif btnp(4) then
      attack(1, dx, dy)
    elseif btnp(6) then
      if P.moving then P.dir = DIRS[dy][dx] end
      shoot()
    elseif btnp(7) then
      P.act = P.ext and "close" or "open"
      play("open", P.ext)
    elseif btnp(5) and not P.moving then
      P.act, P.inv = "backstep", 22
      play(xname("backstep"))
    elseif P.moving then
      local run = btn(5)
      P.dir = DIRS[dy][dx]
      local sp = run and 1.55 or 0.92
      if dx ~= 0 and dy ~= 0 then sp = sp * 0.7071 end
      walk_by(dx * sp, dy * sp)
      if P.anim ~= xname("walk") then play(xname("walk")) end
      step_anim(run and 1.5 or 1)
      if P.newf and (P.f == 3 or P.f == 7) then sfx_step() end
    else
      if P.anim ~= xname("idle") then play(xname("idle")) end
      step_anim()
    end
  elseif act == "attack" then
    local a = HUNT[P.anim]
    local done = step_anim()
    if P.f <= a.hit then forward(P.ext and 0.45 or 0.35) end
    if P.newf and P.f == a.hit then sfx_swing(P.ext) end
    -- the tip of the blade leaves a trail through the blow
    if P.f >= a.hit - 2 and P.f <= a.hit + 1 then
      local fr = a.d[P.dir + 1][P.f]
      P.trail[#P.trail + 1] = { P.x + fr[7], P.y + fr[8], 10 }
    end
    if btnp(4) and P.f >= a.hit - 1 and P.combo < 3 then P.queued = true end
    if P.queued and P.f > a.hit + 1 then
      attack(P.combo + 1, dx, dy)
    elseif done then
      P.act, P.combo = nil, 0
    end
  elseif act == "shoot" then
    local done = step_anim()
    if P.newf and P.f == HUNT[P.anim].fire then fire() end
    if done then P.act = nil end
  elseif act == "open" or act == "close" then
    local done = step_anim()
    if P.newf and P.f == HUNT.open.lock then sfx_clank() end
    if done then P.act, P.ext = nil, act == "open" end
  elseif act == "backstep" then
    local done = step_anim()
    if P.f >= 2 and P.f <= 5 then forward(P.f >= 3 and P.f <= 4 and -2.4 or -1.2) end
    if done then P.act = nil end
  elseif act == "hurt" then
    local done = step_anim()
    if P.f <= 2 then forward(-0.6) end
    if done then P.act = nil end
  elseif act == "down" then
    local done = step_anim()
    if P.f <= 5 then forward(-1.4) end
    if P.newf and P.f == 5 then sfx_fall() end
    if done then P.act, P.lie = "lying", 50 end
  elseif act == "lying" then
    P.lie = P.lie - 1
    if P.lie <= 0 or (P.lie < 30 and (btnp(4) or btnp(5))) then
      P.act = "getup"
      play(xname("getup"))
    end
  elseif act == "getup" then
    if step_anim() then P.act, P.inv = nil, 40 end
  elseif act == "dead" then
    if not step_anim() then
      if P.newf and P.f == 8 then sfx_fall() end
    else
      died_t = died_t + 1
      if died_t > 150 then respawn() end
    end
  end
  for i = #P.trail, 1, -1 do
    local tr = P.trail[i]
    tr[3] = tr[3] - 1
    if tr[3] <= 0 then table.remove(P.trail, i) end
  end

  -- fire burns: braziers and pyres
  if P.act ~= "dead" then
    for cy = pcy - 1, pcy + 1 do
      for cx = pcx - 1, pcx + 1 do
        local ch = chunk(cx, cy)
        if ch and ch.ready then
          for _, f in ipairs(ch.fires) do
            local bx, by = f.x, f.y + (f.big and 10 or 25)
            local r = f.big and 26 or 16
            local ex, ey = (P.x - bx) / r, (P.y - by) / (r * 0.6)
            if ex * ex + ey * ey < 1 then hurt(f.big and 3 or 1, f.big and math.random() < 0.5) end
          end
        end
      end
    end
  end

  -- the camera follows, a little ahead of the hunter
  local tx, ty = P.x - W / 2, P.y - H * 0.62
  cam_x = cam_x + (tx - cam_x) * 0.12
  cam_y = cam_y + (ty - cam_y) * 0.12
  -- a new district: its name
  local d = district(pcx, pcy)
  if d ~= here then
    here = d
    banner, banner_t = d.name, 200
  end
  if banner_t > 0 then banner_t = banner_t - 1 end
end

