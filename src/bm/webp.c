static uint32_t le32(const uint8_t *p)
{
    return (uint32_t)p[0] | (uint32_t)p[1] << 8 | (uint32_t)p[2] << 16 | (uint32_t)p[3] << 24;
}

int webp_is(const uint8_t *buf, size_t len)
{
    return len >= 12 && !memcmp(buf, "RIFF", 4) && !memcmp(buf + 8, "WEBP", 4);
}

enum { KIND_NONE, KIND_LOSSY, KIND_LOSSLESS };

/* Finds the picture chunk. The bytes of a chunk must lie inside the file. */
static int find_image(const uint8_t *buf, size_t len, const uint8_t **data, size_t *size)
{
    size_t pos, end;
    int kind = KIND_NONE;

    if (!webp_is(buf, len))
        return KIND_NONE;
    end = le32(buf + 4);
    if (end < 4 || end > len - 8)
        return KIND_NONE;                       /* truncated or lying size */
    end += 8;
    for (pos = 12; pos + 8 <= end;) {
        uint32_t n = le32(buf + pos + 4);
        const uint8_t *p = buf + pos + 8;
        if (n > end - pos - 8)
            return KIND_NONE;
        if (!memcmp(buf + pos, "VP8X", 4)) {
            if (n < 10 || (p[0] & 0x02))
                return KIND_NONE;               /* animation */
        } else if (!memcmp(buf + pos, "VP8 ", 4)) {
            kind = KIND_LOSSY;
        } else if (!memcmp(buf + pos, "VP8L", 4)) {
            kind = KIND_LOSSLESS;
        }
        if (kind != KIND_NONE) {
            *data = p;
            *size = n;
            return kind;
        }
        pos += 8 + (size_t)n + (n & 1);
    }
    return KIND_NONE;
}

