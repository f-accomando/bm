static inline int clamp255(int v)
{
    return v < 0 ? 0 : v > 255 ? 255 : v;
}

/* a pixel of the plane; outside the picture: 127 above, 129 to the left */
static inline int px_at(const uint8_t *pl, int stride, int x, int y)
{
    if (y < 0)
        return 127;
    if (x < 0)
        return 129;
    return pl[y * stride + x];
}

/* a whole luma (n = 16) or chroma (n = 8) block */
static void pred_block(uint8_t *pl, int stride, int x0, int y0, int n, int mode)
{
    uint8_t top[16], left[16];
    int tl = px_at(pl, stride, x0 - 1, y0 - 1);
    int i, r, c;

    for (i = 0; i < n; i++) {
        top[i] = (uint8_t)px_at(pl, stride, x0 + i, y0 - 1);
        left[i] = (uint8_t)px_at(pl, stride, x0 - 1, y0 + i);
    }
    switch (mode) {
    case V_PRED:
        for (r = 0; r < n; r++)
            memcpy(pl + (y0 + r) * stride + x0, top, (size_t)n);
        break;
    case H_PRED:
        for (r = 0; r < n; r++)
            memset(pl + (y0 + r) * stride + x0, left[r], (size_t)n);
        break;
    case TM_PRED:
        for (r = 0; r < n; r++)
            for (c = 0; c < n; c++)
                pl[(y0 + r) * stride + x0 + c] = (uint8_t)clamp255(left[r] + top[c] - tl);
        break;
    default: {
        int sum = 0, shift = n == 16 ? 3 : 2, v;
        if (y0 > 0)
            for (i = 0; i < n; i++)
                sum += top[i];
        if (x0 > 0)
            for (i = 0; i < n; i++)
                sum += left[i];
        if (y0 > 0 && x0 > 0)
            v = (sum + n) >> (shift + 2);
        else if (y0 > 0 || x0 > 0)
            v = (sum + n / 2) >> (shift + 1);
        else
            v = 128;
        for (r = 0; r < n; r++)
            memset(pl + (y0 + r) * stride + x0, v, (size_t)n);
    }
    }
}

#define AVG3(a, b, c) (((a) + 2 * (b) + (c) + 2) >> 2)
#define AVG2(a, b) (((a) + (b) + 1) >> 1)

/* a 4x4 luma subblock. A[-1] is the corner, A[0..7] the row above (with the
 * four pixels past the block), L[0..3] the column to the left. */
static void pred4(uint8_t *dst, int stride, const uint8_t *A, const uint8_t *L, int mode)
{
    uint8_t B[4][4];
    int E[9], r, c;

    E[0] = L[3]; E[1] = L[2]; E[2] = L[1]; E[3] = L[0];
    E[4] = A[-1];
    E[5] = A[0]; E[6] = A[1]; E[7] = A[2]; E[8] = A[3];

    switch (mode) {
    case B_DC: {
        int v = 4;
        for (r = 0; r < 4; r++)
            v += A[r] + L[r];
        v >>= 3;
        memset(B, v, sizeof B);
        break;
    }
    case B_TM:
        for (r = 0; r < 4; r++)
            for (c = 0; c < 4; c++)
                B[r][c] = (uint8_t)clamp255(L[r] + A[c] - A[-1]);
        break;
    case B_VE:
        for (c = 0; c < 4; c++)
            B[0][c] = B[1][c] = B[2][c] = B[3][c] = (uint8_t)AVG3(A[c - 1], A[c], A[c + 1]);
        break;
    case B_HE:
        B[0][0] = B[0][1] = B[0][2] = B[0][3] = (uint8_t)AVG3(A[-1], L[0], L[1]);
        B[1][0] = B[1][1] = B[1][2] = B[1][3] = (uint8_t)AVG3(L[0], L[1], L[2]);
        B[2][0] = B[2][1] = B[2][2] = B[2][3] = (uint8_t)AVG3(L[1], L[2], L[3]);
        B[3][0] = B[3][1] = B[3][2] = B[3][3] = (uint8_t)AVG3(L[2], L[3], L[3]);
        break;
    case B_LD:
        for (r = 0; r < 4; r++)
            for (c = 0; c < 4; c++) {
                int i = r + c;
                B[r][c] = (uint8_t)(i < 6 ? AVG3(A[i], A[i + 1], A[i + 2]) : AVG3(A[6], A[7], A[7]));
            }
        break;
    case B_RD:
        for (r = 0; r < 4; r++)
            for (c = 0; c < 4; c++) {
                int i = 4 - r + c;
                B[r][c] = (uint8_t)AVG3(E[i - 1], E[i], E[i + 1]);
            }
        break;
    case B_VR:
        B[3][0] = (uint8_t)AVG3(E[1], E[2], E[3]);
        B[2][0] = (uint8_t)AVG3(E[2], E[3], E[4]);
        B[3][1] = B[1][0] = (uint8_t)AVG3(E[3], E[4], E[5]);
        B[2][1] = B[0][0] = (uint8_t)AVG2(E[4], E[5]);
        B[3][2] = B[1][1] = (uint8_t)AVG3(E[4], E[5], E[6]);
        B[2][2] = B[0][1] = (uint8_t)AVG2(E[5], E[6]);
        B[3][3] = B[1][2] = (uint8_t)AVG3(E[5], E[6], E[7]);
        B[2][3] = B[0][2] = (uint8_t)AVG2(E[6], E[7]);
        B[1][3] = (uint8_t)AVG3(E[6], E[7], E[8]);
        B[0][3] = (uint8_t)AVG2(E[7], E[8]);
        break;
    case B_VL:
        B[0][0] = (uint8_t)AVG2(A[0], A[1]);
        B[1][0] = (uint8_t)AVG3(A[0], A[1], A[2]);
        B[2][0] = B[0][1] = (uint8_t)AVG2(A[1], A[2]);
        B[1][1] = B[3][0] = (uint8_t)AVG3(A[1], A[2], A[3]);
        B[2][1] = B[0][2] = (uint8_t)AVG2(A[2], A[3]);
        B[3][1] = B[1][2] = (uint8_t)AVG3(A[2], A[3], A[4]);
        B[2][2] = B[0][3] = (uint8_t)AVG2(A[3], A[4]);
        B[3][2] = B[1][3] = (uint8_t)AVG3(A[3], A[4], A[5]);
        B[2][3] = (uint8_t)AVG3(A[4], A[5], A[6]);
        B[3][3] = (uint8_t)AVG3(A[5], A[6], A[7]);
        break;
    case B_HD:
        B[3][0] = (uint8_t)AVG2(E[0], E[1]);
        B[3][1] = (uint8_t)AVG3(E[0], E[1], E[2]);
        B[2][0] = B[3][2] = (uint8_t)AVG2(E[1], E[2]);
        B[2][1] = B[3][3] = (uint8_t)AVG3(E[1], E[2], E[3]);
        B[2][2] = B[1][0] = (uint8_t)AVG2(E[2], E[3]);
        B[2][3] = B[1][1] = (uint8_t)AVG3(E[2], E[3], E[4]);
        B[1][2] = B[0][0] = (uint8_t)AVG2(E[3], E[4]);
        B[1][3] = B[0][1] = (uint8_t)AVG3(E[3], E[4], E[5]);
        B[0][2] = (uint8_t)AVG3(E[4], E[5], E[6]);
        B[0][3] = (uint8_t)AVG3(E[5], E[6], E[7]);
        break;
    default:    /* B_HU */
        B[0][0] = (uint8_t)AVG2(L[0], L[1]);
        B[0][1] = (uint8_t)AVG3(L[0], L[1], L[2]);
        B[0][2] = B[1][0] = (uint8_t)AVG2(L[1], L[2]);
        B[0][3] = B[1][1] = (uint8_t)AVG3(L[1], L[2], L[3]);
        B[1][2] = B[2][0] = (uint8_t)AVG2(L[2], L[3]);
        B[1][3] = B[2][1] = (uint8_t)AVG3(L[2], L[3], L[3]);
        B[2][2] = B[2][3] = B[3][0] = B[3][1] = B[3][2] = B[3][3] = L[3];
    }
    for (r = 0; r < 4; r++)
        memcpy(dst + r * stride, B[r], 4);
}

