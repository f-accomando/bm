/* ------------------------------------------------------------------ */
/* The boolean entropy decoder (RFC 6386 section 7)                   */
/* ------------------------------------------------------------------ */

typedef struct {
    const uint8_t *p, *end;
    uint32_t value;
    int range, count;
    int over;                   /* bytes asked past the end */
} bd_t;

static uint32_t bd_next(bd_t *d)
{
    if (d->p < d->end)
        return *d->p++;
    d->over++;
    return 0;
}

static void bd_init(bd_t *d, const uint8_t *p, size_t n)
{
    d->p = p;
    d->end = p + n;
    d->over = 0;
    d->value = bd_next(d) << 8;
    d->value |= bd_next(d);
    d->range = 255;
    d->count = 0;
}

static int bd_bit(bd_t *d, int prob)
{
    uint32_t split = 1 + (((uint32_t)(d->range - 1) * (uint32_t)prob) >> 8);
    uint32_t big = split << 8;
    int bit;

    if (d->value >= big) {
        d->range -= (int)split;
        d->value -= big;
        bit = 1;
    } else {
        d->range = (int)split;
        bit = 0;
    }
    while (d->range < 128) {
        d->value <<= 1;
        d->range <<= 1;
        if (++d->count == 8) {
            d->count = 0;
            d->value |= bd_next(d);
        }
    }
    return bit;
}

static int bd_lit(bd_t *d, int n)
{
    int v = 0;
    while (n-- > 0)
        v = (v << 1) | bd_bit(d, 128);
    return v;
}

static int bd_signed(bd_t *d, int n)
{
    int v = bd_lit(d, n);
    return bd_bit(d, 128) ? -v : v;
}

static int bd_tree(bd_t *d, const int8_t *t, const uint8_t *p)
{
    int i = 0;
    while ((i = t[i + bd_bit(d, p[i >> 1])]) > 0)
        ;
    return -i;
}

