typedef uint8_t probs_t[8][3][11];

/* One block. ctx is 0..2 (the neighbours that had coefficients). Returns
 * the position after the last token read (first if there was none). */
static int get_coeffs(bd_t *d, const probs_t P, int ctx, const int *dq, int first, int16_t *out)
{
    int n = first;
    const uint8_t *p = P[coeff_bands[n]][ctx];

    while (n < 16) {
        int v, nctx;
        if (!bd_bit(d, p[0]))
            return n;                           /* end of block */
        while (!bd_bit(d, p[1])) {              /* zeros: no end of block may follow */
            if (++n == 16)
                return 16;
            p = P[coeff_bands[n]][0];
        }
        if (!bd_bit(d, p[2])) {
            v = 1;
            nctx = 1;
        } else {
            nctx = 2;
            if (!bd_bit(d, p[3])) {
                if (!bd_bit(d, p[4]))
                    v = 2;
                else
                    v = 3 + bd_bit(d, p[5]);
            } else if (!bd_bit(d, p[6])) {
                if (!bd_bit(d, p[7])) {
                    v = 5 + bd_bit(d, 159);
                } else {
                    v = 7 + 2 * bd_bit(d, 165);
                    v += bd_bit(d, 145);
                }
            } else {
                int b1 = bd_bit(d, p[8]);
                int cat = 2 * b1 + bd_bit(d, p[9 + b1]);
                const uint8_t *t;
                v = 0;
                for (t = pcat[cat]; *t; t++)
                    v += v + bd_bit(d, *t);
                v += 3 + (8 << cat);
            }
        }
        if (bd_bit(d, 128))
            v = -v;
        out[zigzag[n]] = (int16_t)(v * dq[n > 0]);
        n++;
        p = P[coeff_bands[n]][nctx];
    }
    return 16;
}

