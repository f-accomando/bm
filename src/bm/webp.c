static int vp8_size(const uint8_t *d, size_t n, int *w, int *h)
{
    uint32_t tag;

    if (n < 10)
        return -1;
    tag = (uint32_t)d[0] | (uint32_t)d[1] << 8 | (uint32_t)d[2] << 16;
    if ((tag & 1) || ((tag >> 1) & 7) > 3 || !((tag >> 4) & 1))
        return -1;                              /* not a shown key frame */
    if (d[3] != 0x9d || d[4] != 0x01 || d[5] != 0x2a)
        return -1;
    *w = (d[6] | d[7] << 8) & 0x3fff;
    *h = (d[8] | d[9] << 8) & 0x3fff;
    return *w && *h ? 0 : -1;
}

static int q_clamp(int q)
{
    return q < 0 ? 0 : q > 127 ? 127 : q;
}

static inline void put_rgb(uint16_t *o, int y, int u, int v)
{
    int y1 = 298 * (y - 16) + 128;
    int r = (y1 + 409 * (v - 128)) >> 8;
    int g = (y1 - 100 * (u - 128) - 208 * (v - 128)) >> 8;
    int b = (y1 + 516 * (u - 128)) >> 8;
    r = clamp255(r);
    g = clamp255(g);
    b = clamp255(b);
    *o = (uint16_t)(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3));
}

/* The planes to RGB565. The chroma is smoothed (each output pixel takes
 * 9/16, 3/16, 3/16 and 1/16 of the four nearest chroma samples). */
static void yuv_to_565(const uint8_t *yp, int ys, const uint8_t *up, const uint8_t *vp, int cs, int w, int h,
                       uint16_t *out, int stride, int ow, int oh, uint16_t *vu, uint16_t *vv)
{
    int cw = (w + 1) >> 1, ch = (h + 1) >> 1, px, py, cx;

    for (py = 0; py < oh; py++) {
        int cy = py >> 1, ny = (py & 1) ? cy + 1 : cy - 1;
        const uint8_t *u0, *u1, *v0, *v1, *yr = yp + (size_t)py * ys;
        uint16_t *o = out + (size_t)py * stride;

        if (ny < 0)
            ny = 0;
        if (ny >= ch)
            ny = ch - 1;
        u0 = up + (size_t)cy * cs;
        u1 = up + (size_t)ny * cs;
        v0 = vp + (size_t)cy * cs;
        v1 = vp + (size_t)ny * cs;
        for (cx = 0; cx < (ow + 1) / 2 + 1 && cx < cw; cx++) {
            vu[cx] = (uint16_t)(3 * u0[cx] + u1[cx]);
            vv[cx] = (uint16_t)(3 * v0[cx] + v1[cx]);
        }
        for (px = 0; px < ow; px++) {
            int nx, u, v;
            cx = px >> 1;
            nx = (px & 1) ? cx + 1 : cx - 1;
            if (nx < 0)
                nx = 0;
            if (nx >= cw)
                nx = cw - 1;
            u = (3 * vu[cx] + vu[nx] + 8) >> 4;
            v = (3 * vv[cx] + vv[nx] + 8) >> 4;
            put_rgb(o + px, yr[px], u, v);
        }
    }
}

static int vp8_decode(const uint8_t *d, size_t n, uint16_t *out, int stride, int maxw, int maxh)
{
    static const uint8_t kf_ymode_prob[4] = { 145, 156, 163, 128 };
    static const uint8_t kf_uv_mode_prob[3] = { 142, 114, 183 };
    static const int8_t seg_tree[6] = { 2, 4, -0, -1, -2, -3 };
    static const uint8_t bm_of_ymode[4] = { B_DC, B_VE, B_HE, B_TM };
    int w, h, mbw, mbh, ys, cs, np, i, j, k, l;
    int seg_enabled, update_map = 0, seg_abs = 0, simple, level, sharp, lf_adj, q_index, use_skip, prob_skip = 0;
    int seg_q[4] = { 0, 0, 0, 0 }, seg_lf[4] = { 0, 0, 0, 0 }, ref_d[4] = { 0, 0, 0, 0 }, mode_d[4] = { 0, 0, 0, 0 };
    int dq_delta[5];
    uint8_t seg_prob[3] = { 255, 255, 255 };
    probs_t probs[4];
    quant_t qm[4];
    finfo_t fs[4][2];
    bd_t br, tp[8];
    size_t part1, avail, rem, ysz, csz, total;
    const uint8_t *p;
    uint32_t tag;
    uint8_t *mem = NULL, *yp, *up, *vp, *top_nz, *top_bm;
    uint16_t *vu, *vv;
    finfo_t *info;
    int ret = -1, mx, my, ow, oh;
    uint8_t left_bm[4], left_nz[9];

    if (vp8_size(d, n, &w, &h) < 0)
        return -1;
    if ((size_t)w * (size_t)h > WEBP_MAX_PIXELS)
        return -1;
    tag = (uint32_t)d[0] | (uint32_t)d[1] << 8 | (uint32_t)d[2] << 16;
    part1 = tag >> 5;
    if (part1 > n - 10)
        return -1;

    /* the frame header, in the first partition */
    bd_init(&br, d + 10, part1);
    bd_lit(&br, 2);                             /* color space, clamping type: always clamp */
    seg_enabled = bd_lit(&br, 1);
    if (seg_enabled) {
        int update_data;
        update_map = bd_lit(&br, 1);
        update_data = bd_lit(&br, 1);
        if (update_data) {
            seg_abs = bd_lit(&br, 1);
            for (i = 0; i < 4; i++)
                seg_q[i] = bd_lit(&br, 1) ? bd_signed(&br, 7) : 0;
            for (i = 0; i < 4; i++)
                seg_lf[i] = bd_lit(&br, 1) ? bd_signed(&br, 6) : 0;
        }
        if (update_map)
            for (i = 0; i < 3; i++)
                seg_prob[i] = (uint8_t)(bd_lit(&br, 1) ? bd_lit(&br, 8) : 255);
    }
    simple = bd_lit(&br, 1);
    level = bd_lit(&br, 6);
    sharp = bd_lit(&br, 3);
    lf_adj = bd_lit(&br, 1);
    if (lf_adj && bd_lit(&br, 1)) {
        for (i = 0; i < 4; i++)
            if (bd_lit(&br, 1))
                ref_d[i] = bd_signed(&br, 6);
        for (i = 0; i < 4; i++)
            if (bd_lit(&br, 1))
                mode_d[i] = bd_signed(&br, 6);
    }
    np = 1 << bd_lit(&br, 2);
    q_index = bd_lit(&br, 7);
    for (i = 0; i < 5; i++)
        dq_delta[i] = bd_lit(&br, 1) ? bd_signed(&br, 4) : 0;   /* y dc, y2 dc, y2 ac, uv dc, uv ac */
    bd_lit(&br, 1);                             /* refresh_entropy_probs: one frame, no meaning */
    memcpy(probs, default_coeff_probs, sizeof probs);
    for (i = 0; i < 4; i++)
        for (j = 0; j < 8; j++)
            for (k = 0; k < 3; k++)
                for (l = 0; l < 11; l++)
                    if (bd_bit(&br, coeff_update_probs[((i * 8 + j) * 3 + k) * 11 + l]))
                        probs[i][j][k][l] = (uint8_t)bd_lit(&br, 8);
    use_skip = bd_lit(&br, 1);
    if (use_skip)
        prob_skip = bd_lit(&br, 8);
    if (br.over > 2)
        return -1;

    /* the token partitions */
    avail = n - 10 - part1;
    if (avail < (size_t)3 * (size_t)(np - 1))
        return -1;
    p = d + 10 + part1 + 3 * (np - 1);
    rem = avail - 3 * (size_t)(np - 1);
    for (i = 0; i < np - 1; i++) {
        const uint8_t *s = d + 10 + part1 + 3 * i;
        size_t sz = (size_t)s[0] | (size_t)s[1] << 8 | (size_t)s[2] << 16;
        if (sz > rem)
            return -1;
        bd_init(&tp[i], p, sz);
        p += sz;
        rem -= sz;
    }
    bd_init(&tp[np - 1], p, rem);

    /* the dequantization factors and the loop filter strengths of each segment */
    for (i = 0; i < 4; i++) {
        int q = q_index, base, i4;
        if (seg_enabled)
            q = seg_abs ? seg_q[i] : q_index + seg_q[i];
        qm[i].y1[0] = dc_qlookup[q_clamp(q + dq_delta[0])];
        qm[i].y1[1] = ac_qlookup[q_clamp(q)];
        qm[i].y2[0] = dc_qlookup[q_clamp(q + dq_delta[1])] * 2;
        qm[i].y2[1] = ac_qlookup[q_clamp(q + dq_delta[2])] * 155 / 100;
        if (qm[i].y2[1] < 8)
            qm[i].y2[1] = 8;
        qm[i].uv[0] = dc_qlookup[q_clamp(q + dq_delta[3])];
        if (qm[i].uv[0] > 132)
            qm[i].uv[0] = 132;
        qm[i].uv[1] = ac_qlookup[q_clamp(q + dq_delta[4])];

        base = level;
        if (seg_enabled)
            base = seg_abs ? seg_lf[i] : level + seg_lf[i];
        for (i4 = 0; i4 < 2; i4++) {
            int lv = base, il;
            if (lf_adj) {
                lv += ref_d[0];
                if (i4)
                    lv += mode_d[0];
            }
            lv = lv < 0 ? 0 : lv > 63 ? 63 : lv;
            memset(&fs[i][i4], 0, sizeof fs[i][i4]);
            if (lv > 0) {
                il = lv;
                if (sharp) {
                    il >>= sharp > 4 ? 2 : 1;
                    if (il > 9 - sharp)
                        il = 9 - sharp;
                }
                if (il < 1)
                    il = 1;
                fs[i][i4].ilevel = (uint8_t)il;
                fs[i][i4].limit = (uint8_t)(2 * lv + il);
                fs[i][i4].hevt = (uint8_t)(lv >= 40 ? 2 : lv >= 15 ? 1 : 0);
            }
            fs[i][i4].inner = (uint8_t)i4;
        }
    }

    /* memory: the three planes (whole macroblocks), the filter table, the contexts */
    mbw = (w + 15) >> 4;
    mbh = (h + 15) >> 4;
    ys = mbw * 16;
    cs = mbw * 8;
    ysz = (size_t)ys * (size_t)(mbh * 16);
    csz = (size_t)cs * (size_t)(mbh * 8);
    total = 2 * (size_t)cs * sizeof(uint16_t) + ysz + 2 * csz + (size_t)mbw * (size_t)mbh * sizeof(finfo_t)
          + (size_t)mbw * 9 + (size_t)mbw * 4;
    mem = (uint8_t *)malloc(total);
    if (!mem)
        return -1;
    vu = (uint16_t *)mem;
    vv = vu + cs;
    yp = mem + 2 * (size_t)cs * sizeof(uint16_t);
    up = yp + ysz;
    vp = up + csz;
    info = (finfo_t *)(vp + csz);
    top_nz = (uint8_t *)(info + (size_t)mbw * (size_t)mbh);
    top_bm = top_nz + (size_t)mbw * 9;
    memset(top_nz, 0, (size_t)mbw * 9 + (size_t)mbw * 4);   /* top_bm starts as B_DC (0) */

    for (my = 0; my < mbh; my++) {
        bd_t *tb = &tp[my & (np - 1)];
        memset(left_nz, 0, sizeof left_nz);
        memset(left_bm, 0, sizeof left_bm);
        for (mx = 0; mx < mbw; mx++) {
            int seg = 0, skip, ymode, uvmode, bm[16], has_y2, any = 0, blk;
            int16_t co[25 * 16];
            uint8_t kind[24];
            uint8_t *tnz = top_nz + (size_t)mx * 9, *tbm = top_bm + (size_t)mx * 4;
            const quant_t *q;
            uint8_t *yd = yp + (size_t)my * 16 * ys + mx * 16;
            uint8_t *ud = up + (size_t)my * 8 * cs + mx * 8;
            uint8_t *vd = vp + (size_t)my * 8 * cs + mx * 8;

            if (update_map)
                seg = bd_tree(&br, seg_tree, seg_prob);
            skip = use_skip ? bd_bit(&br, prob_skip) : 0;
            ymode = bd_tree(&br, kf_ymode_tree, kf_ymode_prob);
            if (ymode == B_PRED) {
                for (i = 0; i < 16; i++) {
                    int a = i < 4 ? tbm[i] : bm[i - 4];
                    int lft = (i & 3) ? bm[i - 1] : left_bm[i >> 2];
                    bm[i] = bd_tree(&br, bmode_tree, kf_bmode_prob + (a * 10 + lft) * 9);
                }
            } else {
                for (i = 0; i < 16; i++)
                    bm[i] = bm_of_ymode[ymode];
            }
            for (i = 0; i < 4; i++) {
                tbm[i] = (uint8_t)bm[12 + i];
                left_bm[i] = (uint8_t)bm[4 * i + 3];
            }
            uvmode = bd_tree(&br, uv_mode_tree, kf_uv_mode_prob);

            /* the coefficients */
            memset(co, 0, sizeof co);
            memset(kind, 0, sizeof kind);
            has_y2 = ymode != B_PRED;
            q = &qm[seg_enabled ? seg : 0];
            if (!skip) {
                int first = has_y2 ? 1 : 0, type = has_y2 ? 0 : 3, n2;
                if (has_y2) {
                    int16_t y2[16], dc[16];
                    memset(y2, 0, sizeof y2);
                    n2 = get_coeffs(tb, probs[1], tnz[8] + left_nz[8], q->y2, 0, y2);
                    tnz[8] = left_nz[8] = (uint8_t)(n2 > 0);
                    if (n2 > 0) {
                        inv_wht(y2, dc);
                        for (i = 0; i < 16; i++)
                            co[i * 16] = dc[i];
                    }
                }
                for (blk = 0; blk < 16; blk++) {
                    int bx = blk & 3, by = blk >> 2;
                    n2 = get_coeffs(tb, probs[type], tnz[bx] + left_nz[by], q->y1, first, co + blk * 16);
                    tnz[bx] = left_nz[by] = (uint8_t)(n2 > first);
                    kind[blk] = (uint8_t)(n2 > 1 ? 2 : co[blk * 16] ? 1 : 0);
                }
                for (blk = 16; blk < 24; blk++) {
                    int pl = (blk - 16) >> 2, bx = blk & 1, by = (blk >> 1) & 1;
                    n2 = get_coeffs(tb, probs[2], tnz[4 + 2 * pl + bx] + left_nz[4 + 2 * pl + by], q->uv, 0, co + blk * 16);
                    tnz[4 + 2 * pl + bx] = left_nz[4 + 2 * pl + by] = (uint8_t)(n2 > 0);
                    kind[blk] = (uint8_t)(n2 > 1 ? 2 : co[blk * 16] ? 1 : 0);
                }
                for (blk = 0; blk < 24; blk++)
                    any |= kind[blk];
            } else {
                memset(tnz, 0, 8);
                memset(left_nz, 0, 8);
                if (has_y2)
                    tnz[8] = left_nz[8] = 0;
            }
            info[my * mbw + mx] = fs[seg_enabled ? seg : 0][ymode == B_PRED];
            if (any)
                info[my * mbw + mx].inner = 1;

            /* prediction and reconstruction */
            if (ymode == B_PRED) {
                for (blk = 0; blk < 16; blk++) {
                    int bx = blk & 3, by = blk >> 2;
                    int x = mx * 16 + bx * 4, yy = my * 16 + by * 4;
                    uint8_t Ab[9], L[4], *A = Ab + 1, *dst = yp + (size_t)yy * ys + x;
                    A[-1] = (uint8_t)px_at(yp, ys, x - 1, yy - 1);
                    for (i = 0; i < 4; i++) {
                        A[i] = (uint8_t)px_at(yp, ys, x + i, yy - 1);
                        L[i] = (uint8_t)px_at(yp, ys, x - 1, yy + i);
                    }
                    if (yy == 0 || (bx == 3 && by > 0 && my == 0)) {
                        memset(A + 4, 127, 4);
                    } else if (bx == 3 && mx == mbw - 1) {
                        /* last column: the pixel above the macroblock's right edge repeats */
                        memset(A + 4, yp[(size_t)(my * 16 - 1) * ys + mx * 16 + 15], 4);
                    } else if (bx == 3 && by > 0) {
                        memcpy(A + 4, yp + (size_t)(my * 16 - 1) * ys + mx * 16 + 16, 4);
                    } else {
                        memcpy(A + 4, yp + (size_t)(yy - 1) * ys + x + 4, 4);
                    }
                    pred4(dst, ys, A, L, bm[blk]);
                    if (kind[blk] == 2)
                        idct_add(co + blk * 16, dst, ys);
                    else if (kind[blk] == 1)
                        dc_add(co[blk * 16], dst, ys);
                }
            } else {
                pred_block(yp, ys, mx * 16, my * 16, 16, ymode);
                for (blk = 0; blk < 16; blk++) {
                    uint8_t *dst = yd + (blk >> 2) * 4 * ys + (blk & 3) * 4;
                    if (kind[blk] == 2)
                        idct_add(co + blk * 16, dst, ys);
                    else if (kind[blk] == 1)
                        dc_add(co[blk * 16], dst, ys);
                }
            }
            pred_block(up, cs, mx * 8, my * 8, 8, uvmode);
            pred_block(vp, cs, mx * 8, my * 8, 8, uvmode);
            for (blk = 16; blk < 24; blk++) {
                uint8_t *base = blk < 20 ? ud : vd;
                uint8_t *dst = base + ((blk >> 1) & 1) * 4 * cs + (blk & 1) * 4;
                if (kind[blk] == 2)
                    idct_add(co + blk * 16, dst, cs);
                else if (kind[blk] == 1)
                    dc_add(co[blk * 16], dst, cs);
            }
        }
        if (br.over > 2 || tb->over > 2)
            goto done;                          /* the data ended inside the picture */
    }

    /* the loop filter, after the whole picture is built */
    if (level > 0) {
        for (my = 0; my < mbh; my++)
            for (mx = 0; mx < mbw; mx++) {
                const finfo_t *f = &info[my * mbw + mx];
                uint8_t *yd = yp + (size_t)my * 16 * ys + mx * 16;
                uint8_t *ud = up + (size_t)my * 8 * cs + mx * 8;
                uint8_t *vd = vp + (size_t)my * 8 * cs + mx * 8;
                int E = f->limit, I = f->ilevel, T = f->hevt;
                if (!E)
                    continue;
                if (simple) {
                    if (mx > 0)
                        edge_simple(yd, ys, 1, 16, E + 4);
                    if (f->inner)
                        for (k = 4; k < 16; k += 4)
                            edge_simple(yd + k, ys, 1, 16, E);
                    if (my > 0)
                        edge_simple(yd, 1, ys, 16, E + 4);
                    if (f->inner)
                        for (k = 4; k < 16; k += 4)
                            edge_simple(yd + k * ys, 1, ys, 16, E);
                    continue;
                }
                if (mx > 0) {
                    edge_mb(yd, ys, 1, 16, T, I, E + 4);
                    edge_mb(ud, cs, 1, 8, T, I, E + 4);
                    edge_mb(vd, cs, 1, 8, T, I, E + 4);
                }
                if (f->inner) {
                    for (k = 4; k < 16; k += 4)
                        edge_sub(yd + k, ys, 1, 16, T, I, E);
                    edge_sub(ud + 4, cs, 1, 8, T, I, E);
                    edge_sub(vd + 4, cs, 1, 8, T, I, E);
                }
                if (my > 0) {
                    edge_mb(yd, 1, ys, 16, T, I, E + 4);
                    edge_mb(ud, 1, cs, 8, T, I, E + 4);
                    edge_mb(vd, 1, cs, 8, T, I, E + 4);
                }
                if (f->inner) {
                    for (k = 4; k < 16; k += 4)
                        edge_sub(yd + k * ys, 1, ys, 16, T, I, E);
                    edge_sub(ud + 4 * cs, 1, cs, 8, T, I, E);
                    edge_sub(vd + 4 * cs, 1, cs, 8, T, I, E);
                }
            }
    }

    ow = w < maxw ? w : maxw;
    oh = h < maxh ? h : maxh;
    if (ow > 0 && oh > 0)
        yuv_to_565(yp, ys, up, vp, cs, w, h, out, stride, ow, oh, vu, vv);
    ret = 0;
done:
    free(mem);
    return ret;
}

