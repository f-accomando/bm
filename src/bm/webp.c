int webp_info(const uint8_t *buf, size_t len, int *w, int *h)
{
    const uint8_t *d;
    size_t n;
    int kind = find_image(buf, len, &d, &n);

    if (kind == KIND_LOSSY)
        return vp8_size(d, n, w, h);
    if (kind == KIND_LOSSLESS)
        return vp8l_size(d, n, w, h);
    return -1;
}

int webp_decode565(const uint8_t *buf, size_t len, uint16_t *out, int stride, int maxw, int maxh)
{
    const uint8_t *d;
    size_t n;
    int kind = find_image(buf, len, &d, &n);

    if (!out || stride < 0)
        return -1;
    if (kind == KIND_LOSSY)
        return vp8_decode(d, n, out, stride, maxw, maxh);
    if (kind == KIND_LOSSLESS)
        return vp8l_decode(d, n, out, stride, maxw, maxh);
    return -1;
}

