static inline int sc(int v)     /* clamp to int8 */
{
    return v < -128 ? -128 : v > 127 ? 127 : v;
}

static inline int iabs(int v)
{
    return v < 0 ? -v : v;
}

/* the common adjustment; returns the amount taken off q0 */
static int common_adjust(int outer, uint8_t *P1, uint8_t *P0, uint8_t *Q0, uint8_t *Q1)
{
    int p1 = *P1 - 128, p0 = *P0 - 128, q0 = *Q0 - 128, q1 = *Q1 - 128;
    int a = sc((outer ? sc(p1 - q1) : 0) + 3 * (q0 - p0));
    int b = sc(a + 3) >> 3;
    a = sc(a + 4) >> 3;
    *Q0 = (uint8_t)(sc(q0 - a) + 128);
    *P0 = (uint8_t)(sc(p0 + b) + 128);
    return a;
}

/* q points at the pixel after the edge (q0); s steps across the edge */
static void simple_seg(uint8_t *q, int s, int edge)
{
    if (iabs(q[-s] - q[0]) * 2 + iabs(q[-2 * s] - q[s]) / 2 <= edge)
        common_adjust(1, q - 2 * s, q - s, q, q + s);
}

static int filter_yes(int I, int E, const uint8_t *q, int s)
{
    int p3 = q[-4 * s], p2 = q[-3 * s], p1 = q[-2 * s], p0 = q[-s];
    int q0 = q[0], q1 = q[s], q2 = q[2 * s], q3 = q[3 * s];
    return iabs(p0 - q0) * 2 + iabs(p1 - q1) / 2 <= E
        && iabs(p3 - p2) <= I && iabs(p2 - p1) <= I && iabs(p1 - p0) <= I
        && iabs(q3 - q2) <= I && iabs(q2 - q1) <= I && iabs(q1 - q0) <= I;
}

static int hev(const uint8_t *q, int s, int t)
{
    return iabs(q[-2 * s] - q[-s]) > t || iabs(q[s] - q[0]) > t;
}

static void sub_seg(uint8_t *q, int s, int hevt, int I, int E)
{
    if (filter_yes(I, E, q, s)) {
        int hv = hev(q, s, hevt);
        int p1 = q[-2 * s] - 128, q1 = q[s] - 128;
        int a = (common_adjust(hv, q - 2 * s, q - s, q, q + s) + 1) >> 1;
        if (!hv) {
            q[s] = (uint8_t)(sc(q1 - a) + 128);
            q[-2 * s] = (uint8_t)(sc(p1 + a) + 128);
        }
    }
}

static void mb_seg(uint8_t *q, int s, int hevt, int I, int E)
{
    if (filter_yes(I, E, q, s)) {
        if (!hev(q, s, hevt)) {
            int p2 = q[-3 * s] - 128, p1 = q[-2 * s] - 128, p0 = q[-s] - 128;
            int q0 = q[0] - 128, q1 = q[s] - 128, q2 = q[2 * s] - 128;
            int w = sc(sc(p1 - q1) + 3 * (q0 - p0));
            int a = sc((27 * w + 63) >> 7);
            q[0] = (uint8_t)(sc(q0 - a) + 128);
            q[-s] = (uint8_t)(sc(p0 + a) + 128);
            a = sc((18 * w + 63) >> 7);
            q[s] = (uint8_t)(sc(q1 - a) + 128);
            q[-2 * s] = (uint8_t)(sc(p1 + a) + 128);
            a = sc((9 * w + 63) >> 7);
            q[2 * s] = (uint8_t)(sc(q2 - a) + 128);
            q[-3 * s] = (uint8_t)(sc(p2 + a) + 128);
        } else {
            common_adjust(1, q - 2 * s, q - s, q, q + s);
        }
    }
}

/* n pixels along an edge: step is the distance between two of them, s
 * the distance across the edge */
static void edge_mb(uint8_t *q, int step, int s, int n, int hevt, int I, int E)
{
    while (n-- > 0) {
        mb_seg(q, s, hevt, I, E);
        q += step;
    }
}

static void edge_sub(uint8_t *q, int step, int s, int n, int hevt, int I, int E)
{
    while (n-- > 0) {
        sub_seg(q, s, hevt, I, E);
        q += step;
    }
}

static void edge_simple(uint8_t *q, int step, int s, int n, int E)
{
    while (n-- > 0) {
        simple_seg(q, s, E);
        q += step;
    }
}

