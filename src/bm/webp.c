static void inv_wht(const int16_t *in, int16_t *out)
{
    int16_t t[16];
    int i;

    for (i = 0; i < 4; i++) {
        int a1 = in[i] + in[12 + i], b1 = in[4 + i] + in[8 + i];
        int c1 = in[4 + i] - in[8 + i], d1 = in[i] - in[12 + i];
        t[i] = (int16_t)(a1 + b1);
        t[4 + i] = (int16_t)(c1 + d1);
        t[8 + i] = (int16_t)(a1 - b1);
        t[12 + i] = (int16_t)(d1 - c1);
    }
    for (i = 0; i < 4; i++) {
        int a1 = t[4 * i] + t[4 * i + 3], b1 = t[4 * i + 1] + t[4 * i + 2];
        int c1 = t[4 * i + 1] - t[4 * i + 2], d1 = t[4 * i] - t[4 * i + 3];
        out[4 * i] = (int16_t)((a1 + b1 + 3) >> 3);
        out[4 * i + 1] = (int16_t)((c1 + d1 + 3) >> 3);
        out[4 * i + 2] = (int16_t)((a1 - b1 + 3) >> 3);
        out[4 * i + 3] = (int16_t)((d1 - c1 + 3) >> 3);
    }
}

/* the residue added to the 4x4 block at dst */
static void idct_add(const int16_t *in, uint8_t *dst, int stride)
{
    int16_t t[16];
    int i, r, c;

    for (i = 0; i < 4; i++) {
        int a1 = in[i] + in[8 + i], b1 = in[i] - in[8 + i];
        int c1 = ((in[4 + i] * 35468) >> 16) - (in[12 + i] + ((in[12 + i] * 20091) >> 16));
        int d1 = (in[4 + i] + ((in[4 + i] * 20091) >> 16)) + ((in[12 + i] * 35468) >> 16);
        t[i] = (int16_t)(a1 + d1);
        t[12 + i] = (int16_t)(a1 - d1);
        t[4 + i] = (int16_t)(b1 + c1);
        t[8 + i] = (int16_t)(b1 - c1);
    }
    for (r = 0; r < 4; r++) {
        const int16_t *ip = t + 4 * r;
        int a1 = ip[0] + ip[2], b1 = ip[0] - ip[2];
        int c1 = ((ip[1] * 35468) >> 16) - (ip[3] + ((ip[3] * 20091) >> 16));
        int d1 = (ip[1] + ((ip[1] * 20091) >> 16)) + ((ip[3] * 35468) >> 16);
        int v[4];
        v[0] = (a1 + d1 + 4) >> 3;
        v[3] = (a1 - d1 + 4) >> 3;
        v[1] = (b1 + c1 + 4) >> 3;
        v[2] = (b1 - c1 + 4) >> 3;
        for (c = 0; c < 4; c++)
            dst[r * stride + c] = (uint8_t)clamp255(dst[r * stride + c] + v[c]);
    }
}

static void dc_add(int dc, uint8_t *dst, int stride)
{
    int v = (dc + 4) >> 3, r, c;
    for (r = 0; r < 4; r++)
        for (c = 0; c < 4; c++)
            dst[r * stride + c] = (uint8_t)clamp255(dst[r * stride + c] + v);
}

