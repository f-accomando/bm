-- 65C816 core tests. Run: lua cpu_test.lua  (the harness script glues carts/snes/src/01+02 and this file)
-- Each test: bytes of a program placed at $00:8000, run until STP, then compare registers.
local fails, count = 0, 0
local function prog(bytes)
  local t = {}
  for i = 1, 0x8000 do t[i] = "\0" end
  for i, b in ipairs(bytes) do t[i] = string.char(b) end
  t[0x7FFD] = "\x00"; t[0x7FFE] = "\x80"            -- reset vector $8000 (file offset $7FFC..$7FFD)
  rom = table.concat(t); romsize = #rom; lorom = true; sramsize = 0
  for i = 1, 131072 do WRAM[i] = 0 end
  cpu_reset()
  local steps = 0
  while not stopped and steps < 10000 do cpu_run(cyc + 4); steps = steps + 1 end
end
local function check(name, cond, extra)
  count = count + 1
  if not cond then fails = fails + 1; print("FAIL " .. name .. (extra and (" " .. extra) or "")) end
end

-- native mode, 16-bit A: LDA #$1234 / CLC / ADC #$0001
prog{0x18,0xFB, 0xC2,0x30, 0xA9,0x34,0x12, 0x18, 0x69,0x01,0x00, 0xDB}
check("adc16", A == 0x1235 and fC == 0 and fZ == 0 and fN == 0 and fE == 0, string.format("A=%04X", A))

-- 8-bit carry out: LDA #$FF / ADC #$01 (m=1 in emulation mode)
prog{0x18, 0xA9,0xFF, 0x69,0x01, 0xDB}
check("adc8 carry", (A & 0xFF) == 0 and fC == 1 and fZ == 1)

-- overflow: $50 + $50 = $A0, V=1 N=1
prog{0x18, 0xA9,0x50, 0x69,0x50, 0xDB}
check("adc ov", (A & 0xFF) == 0xA0 and fV == 1 and fN == 1 and fC == 0)

-- SBC: $50 - $F0 = $60, C clear (borrow)
prog{0x38, 0xA9,0x50, 0xE9,0xF0, 0xDB}
check("sbc", (A & 0xFF) == 0x60 and fC == 0 and fV == 0, string.format("A=%02X C=%d V=%d", A & 0xFF, fC, fV))

-- BCD: SED / CLC / LDA #$19 / ADC #$28 -> $47
prog{0xF8, 0x18, 0xA9,0x19, 0x69,0x28, 0xDB}
check("bcd add", (A & 0xFF) == 0x47 and fC == 0, string.format("A=%02X", A & 0xFF))
prog{0xF8, 0x18, 0xA9,0x99, 0x69,0x01, 0xDB}
check("bcd carry", (A & 0xFF) == 0x00 and fC == 1)
prog{0xF8, 0x38, 0xA9,0x47, 0xE9,0x28, 0xDB}
check("bcd sub", (A & 0xFF) == 0x19 and fC == 1, string.format("A=%02X C=%d", A & 0xFF, fC))

-- loop: LDX #$0005 (16-bit) ; DEX ; BNE
prog{0x18,0xFB, 0xC2,0x10, 0xA2,0x05,0x00, 0xCA, 0xD0,0xFD, 0xDB}
check("dex loop", X == 0 and fZ == 1)

-- JSR / RTS and stack
prog{0x20,0x08,0x80, 0xA9,0x11, 0xDB, 0xEA, 0xEA,   -- JSR $8008; LDA #$11; STP
     0xA9,0x22, 0x60}                                  -- $8008: LDA #$22; RTS
check("jsr rts", (A & 0xFF) == 0x11 and S == 0x1FF, string.format("A=%02X S=%04X", A & 0xFF, S))

-- PHA / PLA, TAX, XBA
prog{0xA9,0x12, 0x48, 0xA9,0x00, 0x68, 0xAA, 0xEB, 0xDB}
check("pha pla", X == 0x12 and (A & 0xFF) == 0x00 and ((A >> 8) & 0xFF) == 0x12)

-- store and load WRAM; dp,X ; (dp),Y
prog{0xA9,0x77, 0x85,0x10,                       -- LDA #$77; STA $10
     0xA2,0x02, 0xA9,0x55, 0x95,0x10,           -- LDX #2; LDA #$55; STA $10,X
     0xA9,0x20, 0x85,0x20, 0xA9,0x00, 0x85,0x21, -- ptr $20 = $0020 (points at itself area)
     0xA0,0x01, 0xB1,0x20, 0xDB}                 -- LDY #1; LDA ($20),Y
check("wram", WRAM[0x10 + 1] == 0x77 and WRAM[0x12 + 1] == 0x55)
check("(dp),y", (A & 0xFF) == 0x00, string.format("A=%02X", A & 0xFF))  -- $0021 = 0

-- long addressing: LDA $7E1234 / STA $7F0001
prog{0xA9,0x5A, 0x8F,0x34,0x12,0x7E, 0xA9,0x00, 0xAF,0x34,0x12,0x7E, 0x8F,0x01,0x00,0x7F, 0xDB}
check("long", WRAM[0x1234 + 1] == 0x5A and WRAM[0x10001 + 1] == 0x5A and (A & 0xFF) == 0x5A)

-- MVN: copy 4 bytes from $7E:0100 to $7E:0200
prog{0x18,0xFB, 0xC2,0x30,
     0xA9,0x01,0x02, 0x8D,0x00,0x01,            -- LDA #$0201 ; STA $0100 (16-bit store)  bytes 01 02
     0xA9,0x03,0x04, 0x8D,0x02,0x01,            -- bytes 03 04 at $0102
     0xA2,0x00,0x01, 0xA0,0x00,0x02, 0xA9,0x03,0x00, -- X=$0100 Y=$0200 A=3 (count-1)
     0x54,0x7E,0x7E, 0xDB}                       -- MVN 7E,7E
check("mvn", WRAM[0x200 + 1] == 1 and WRAM[0x201 + 1] == 2 and WRAM[0x202 + 1] == 3 and WRAM[0x203 + 1] == 4
  and A == 0xFFFF, string.format("%d %d %d %d A=%04X", WRAM[0x201], WRAM[0x202], WRAM[0x203], WRAM[0x204], A))

-- shifts: ASL A with carry, ROR through carry
prog{0x18, 0xA9,0x81, 0x0A, 0x6A, 0xDB}          -- ASL -> $02 C=1 ; ROR -> $81 C=0
check("asl ror", (A & 0xFF) == 0x81 and fC == 0 and fN == 1, string.format("A=%02X C=%d", A & 0xFF, fC))

-- compare and branch
prog{0xA9,0x10, 0xC9,0x10, 0xF0,0x02, 0xA9,0xFF, 0xDB}   -- BEQ skips LDA #$FF
check("cmp beq", (A & 0xFF) == 0x10 and fC == 1 and fZ == 1)

-- REP / SEP and XCE: native 16-bit index, then back to 8-bit clears the high byte
prog{0x18,0xFB, 0xC2,0x10, 0xA2,0x34,0x12, 0xE2,0x10, 0xDB}
check("sep x", X == 0x34 and fX == 1)

-- TSB / TRB / BIT
prog{0xA9,0x0F, 0x85,0x30, 0xA9,0xF0, 0x04,0x30, 0xDB}      -- TSB $30 : mem |= A ; Z set (no overlap)
check("tsb", WRAM[0x30 + 1] == 0xFF and fZ == 1)

-- JML / RTL
prog{0x22,0x10,0x80,0x00, 0xA9,0x33, 0xDB, 0xEA, 0xEA, 0xEA, 0xEA, 0xEA, 0xEA, 0xEA, 0xEA, 0xEA,
     0xA9,0x44, 0x6B}                                        -- $8010: LDA #$44; RTL
check("jsl rtl", (A & 0xFF) == 0x33, string.format("A=%02X", A & 0xFF))

-- multiply unit through the bus: $4202/$4203 -> $4216/7
prog{0xA9,0x07, 0x8D,0x02,0x42, 0xA9,0x09, 0x8D,0x03,0x42, 0xAD,0x16,0x42, 0xDB}
check("mul", (A & 0xFF) == 63, string.format("A=%d", A & 0xFF))

-- divide unit: 1000 / 7 = 142 r 6
prog{0xA9,0xE8, 0x8D,0x04,0x42, 0xA9,0x03, 0x8D,0x05,0x42, 0xA9,0x07, 0x8D,0x06,0x42, 0xAD,0x14,0x42, 0xDB}
check("div", (A & 0xFF) == 142, string.format("A=%d", A & 0xFF))

print(string.format("%d checks, %d failed", count, fails))
os.exit(fails == 0 and 0 or 1)
