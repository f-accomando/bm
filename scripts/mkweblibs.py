#!/usr/bin/env python3
"""
mkweblibs.py - writes a C file with the Lua libraries of require() (src/bm/require.c)
for the WebAssembly build. tests/host/libs.S does the same with .incbin, which wasm
cannot assemble. Standard library only.

  mkweblibs.py -o build/web/libs.c --words build/words.lua
"""
import argparse
import os
import sys

LIBS = [("assist", "src/ai/assist.lua"), ("bm3d", "src/script/bm3d.lua"), ("bmlib", "src/script/bmlib.lua"),
        ("bmnet", "src/script/bmnet.lua"), ("predict", "src/ai/predict.lua"), ("words", None),
        ("padtype", "src/ai/padtype.lua"), ("riff", "src/script/riff.lua"), ("bmui", "src/script/bmui.lua")]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--words", required=True, help="build/words.lua")
    a = ap.parse_args()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = ["/* generated by scripts/mkweblibs.py: do not edit */", "#include <stdint.h>", "",
           "const uint8_t bm_libs[] __attribute__((aligned(4))) = {"]
    syms, pos = [], 0
    for name, path in LIBS:
        p = a.words if path is None else os.path.join(root, path)
        with open(p, "rb") as f:
            data = f.read() + bytes(1)
        for i in range(0, len(data), 24):
            out.append(",".join(str(b) for b in data[i:i + 24]) + ",")
        syms.append((name, pos, pos + len(data) - 1))
        pos += len(data)
    out.append("0};")
    # wasm-ld has no --defsym: the symbols of require.c are labels inside one array
    nl = chr(92) + "n"
    out.append("__asm__(")
    for name, start, end in syms:
        out.append('    ".globl bm_lib_%s%s.set bm_lib_%s, bm_libs+%d%s"' % (name, nl, name, start, nl))
        out.append('    ".globl bm_lib_%s_end%s.set bm_lib_%s_end, bm_libs+%d%s"' % (name, nl, name, end, nl))
    out.append(");")
    os.makedirs(os.path.dirname(os.path.abspath(a.output)), exist_ok=True)
    with open(a.output, "w", newline=chr(10)) as f:
        f.write(chr(10).join(out) + chr(10))


if __name__ == "__main__":
    sys.exit(main())
