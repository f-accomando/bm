#!/usr/bin/env python3
"""Generates src/ai/api.tsv from docs/api/*.md.

One line per signature: a name documented with several signatures (music(n), music(-1), music())
has several lines, in the order of the docs. The same signature seen twice is reported as dup."""
import argparse
import glob
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

ROW_RE = re.compile(r"^\| (.+?) \| (.*) \|\s*$")
SIG_RE = re.compile(r"^(?:[A-Za-z_]\w*(?:\s*,\s*[A-Za-z_]\w*)*\s*=\s*)?([A-Za-z_]\w*(?:[.:][A-Za-z_]\w*)*)\s*\(.*\)$")
BACKTICK_RE = re.compile(r"`([^`]+)`")


def parse_md_file(fpath, entries, err_stream=sys.stderr, rel_path=None):
    if rel_path is None:
        try:
            rel_path = os.path.relpath(fpath, ROOT).replace("\\", "/")
        except ValueError:
            rel_path = fpath.replace("\\", "/")
    area = os.path.splitext(os.path.basename(fpath))[0]
    with open(fpath, "r", encoding="utf-8") as f:
        for lno, line in enumerate(f, 1):
            m = ROW_RE.match(line)
            if not m:
                continue
            first_cell, second_cell = m.group(1), m.group(2)
            spans = BACKTICK_RE.findall(first_cell)
            for span in spans:
                m_sig = SIG_RE.match(span)
                if not m_sig:
                    continue
                name = m_sig.group(1)
                sig = span
                text = second_cell.replace("\t", " ").replace("\r", " ").replace("\n", " ")
                forms = entries.setdefault(name, [])
                if any(x["signature"] == sig for x in forms):
                    # the same signature twice: the first one stays
                    if err_stream is not None:
                        err_stream.write(f"dup {name} {rel_path}:{lno}\n")
                else:
                    # a name with several signatures keeps each of them, in the order of the docs
                    forms.append({
                        "name": name,
                        "signature": sig,
                        "area": area,
                        "text": text,
                    })


def parse_api_docs(docs_dir=None, err_stream=sys.stderr):
    if docs_dir is None:
        docs_dir = os.path.join(ROOT, "docs", "api")
    entries = {}
    pattern = os.path.join(docs_dir, "*.md")
    files = sorted(glob.glob(pattern))
    for fpath in files:
        parse_md_file(fpath, entries, err_stream=err_stream)
    return entries


def format_tsv(entries):
    lines = ["# generated by scripts/mkapi.py from docs/api/*.md: do not edit\n"]
    for name in sorted(entries.keys()):
        for e in entries[name]:     # one line per signature of the name
            lines.append(f"{e['name']}\t{e['signature']}\t{e['area']}\t{e['text']}\n")
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate src/ai/api.tsv from docs/api/*.md")
    parser.add_argument("--check", action="store_true", help="Exit 1 if api.tsv is stale")
    parser.add_argument("--names", action="store_true", help="Print function names, one per line")
    parser.add_argument("--docs-dir", default=None, help="Custom docs/api directory")
    parser.add_argument("--out", default=None, help="Custom output file")
    args = parser.parse_args()

    tsv_path = args.out or os.path.join(ROOT, "src", "ai", "api.tsv")
    entries = parse_api_docs(args.docs_dir)

    if args.names:
        for name in sorted(entries.keys()):
            sys.stdout.write(f"{name}\n")
        return 0

    content = format_tsv(entries)

    if args.check:
        if not os.path.exists(tsv_path):
            sys.stderr.write("api.tsv is stale\n")
            return 1
        with open(tsv_path, "r", encoding="utf-8") as f:
            existing = f.read()
        if existing != content:
            sys.stderr.write("api.tsv is stale\n")
            return 1
        return 0

    os.makedirs(os.path.dirname(tsv_path), exist_ok=True)
    with open(tsv_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
