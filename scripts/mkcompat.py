#!/usr/bin/env python3
"""mkcompat.py - makes src/bm/compat_table.h, the C form of docs/spec/compat-policy.toml.

  python scripts/mkcompat.py            write src/bm/compat_table.h
  python scripts/mkcompat.py --check    exit 1 if the file is not what the table gives (make test-compat does this)

The toml is the source of truth. Both kernels read the C table through bm_compat_classify (src/bm/format.c).
The table is checked by scripts/bm_weight.py load_policy (keys, actions, reason length), so a wrong table stops here.
Standard library only."""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import bm_weight  # noqa: E402

OUT = os.path.join(ROOT, "src", "bm", "compat_table.h")
ACT = {"show": "BM_ACT_SHOW", "grey": "BM_ACT_GREY", "hide": "BM_ACT_HIDE"}
EDITION = {"bm": "BM_EDITION_BM", "b16": "BM_EDITION_B16", "project": "BM_EDITION_PROJECT"}


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def tri(rule, key):
    """a true/false key as 0 (absent), 1 (must be false), 2 (must be true)"""
    return 0 if key not in rule else (2 if rule[key] else 1)


def generate(policy):
    kernels = list(policy["kernels"].values())
    rules = policy["rules"]
    L = ["/* GENERATED by scripts/mkcompat.py from docs/spec/compat-policy.toml. Do not edit: change the toml, run the script.",
         " * Included by src/bm/format.c only. A rule matches when every key it has matches; the first rule of a kernel wins. */", ""]
    L.append("static const bm_policy_kernel_t bm_policy_kernels[] = {")
    for k in kernels:
        L.append(f"    {{ {k['target']}, {ACT[k['default_action']]}, {c_str(k['default_reason'])} }},   /* {k['id']} */")
    L.append("};")
    L.append("")
    for i, r in enumerate(rules):
        if "res" in r:
            vals = []
            for s in r["res"]:
                w, h = s.split("x")
                vals.append(f"{int(w)}u << 16 | {int(h)}u")
            L.append(f"static const uint32_t bm_policy_res_{i}[] = {{ {', '.join(vals)} }};")
    L.append("")
    L.append("static const bm_policy_rule_t bm_policy_rules[] = {")
    L.append("    /* kernel, action, market, edition, declared, not_listed, uses_3d, res, nres, audio_over, size_over_mib, reason */")
    for i, r in enumerate(rules):
        k = policy["kernels"][r["kernel"]]
        res = f"bm_policy_res_{i}, {len(r['res'])}" if "res" in r else "0, 0"
        ed = EDITION[r["edition"]] if "edition" in r else "BM_EDITION_ANY"
        audio = r.get("audio_bytes_over", -1)
        size = r.get("size_over_mib", -1)
        L.append(f"    {{ {k['target']}, {ACT[r['action']]}, {ACT[r.get('market_action', r['action'])]}, {ed}, "
                 f"{tri(r, 'declared')}, {tri(r, 'kernel_not_listed')}, {tri(r, 'uses_3d')}, {res}, "
                 f"{audio}, {size}, {c_str(r['reason'])} }},   /* {i + 1} */")
    L.append("};")
    L.append("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="Exit 1 if src/bm/compat_table.h is stale")
    ap.add_argument("--policy", default=bm_weight.POLICY_PATH)
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    text = generate(bm_weight.load_policy(a.policy))
    if a.check:
        try:
            with open(a.out, "r", encoding="utf-8", newline="") as f:
                old = f.read()
        except OSError:
            old = None
        if old != text:
            print(f"mkcompat: {os.path.relpath(a.out, ROOT)} is not what docs/spec/compat-policy.toml gives: "
                  "run python scripts/mkcompat.py", file=sys.stderr)
            return 1
        print("mkcompat: the C table is current")
        return 0
    with open(a.out, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print(f"mkcompat: wrote {os.path.relpath(a.out, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
