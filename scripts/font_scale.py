#!/usr/bin/env python3
"""
Scales a 1-bit console font C source (such as src/gfx/font8x16.c) by 2x or 3x
with Scale2x / Scale3x (AdvMAME2x / AdvMAME3x), so vertical and horizontal
strokes stay sharp on the grid while diagonals and curves step by one pixel.

Usage:
  python3 scripts/font_scale.py src/gfx/font8x16.c 2 > src/gfx/font16x32.c
  python3 scripts/font_scale.py src/gfx/font8x16.c 3 > src/gfx/font24x48.c
  python3 scripts/font_scale.py   # writes both font16x32.c and font24x48.c
"""
import os
import re
import sys


def parse_font_c(path):
    text = open(path, "r", encoding="utf-8").read()
    m_wh = re.search(r"\.width\s*=\s*(\d+),\s*\.height\s*=\s*(\d+)", text)
    if not m_wh:
        raise SystemExit(f"{path}: cannot find .width / .height")
    w, h = int(m_wh.group(1)), int(m_wh.group(2))
    rows = re.findall(r"\{\s*((?:0x[0-9a-fA-F]{2}\s*,\s*)*0x[0-9a-fA-F]{2})\s*\}", text)
    if len(rows) != 256:
        raise SystemExit(f"{path}: expected 256 glyphs, found {len(rows)}")
    glyphs = []
    for r in rows:
        vals = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]{2}", r)]
        if len(vals) != h:
            raise SystemExit(f"{path}: expected {h} bytes per glyph, got {len(vals)}")
        grid = [[(vals[y] >> (7 - x)) & 1 for x in range(w)] for y in range(h)]
        glyphs.append(grid)
    return w, h, glyphs


def at(g, x, y, w, h):
    if 0 <= x < w and 0 <= y < h:
        return g[y][x]
    return 0


def scale2x(g, w, h):
    out = [[0] * (w * 2) for _ in range(h * 2)]
    for y in range(h):
        for x in range(w):
            p = at(g, x, y, w, h)
            a = at(g, x, y - 1, w, h)
            b = at(g, x + 1, y, w, h)
            c = at(g, x - 1, y, w, h)
            d = at(g, x, y + 1, w, h)
            if c != b and a != d:
                e0 = a if a == c else p
                e1 = b if a == b else p
                e2 = c if d == c else p
                e3 = b if d == b else p
            else:
                e0 = e1 = e2 = e3 = p
            out[2 * y][2 * x] = e0
            out[2 * y][2 * x + 1] = e1
            out[2 * y + 1][2 * x] = e2
            out[2 * y + 1][2 * x + 1] = e3
    return out


def scale3x(g, w, h):
    out = [[0] * (w * 3) for _ in range(h * 3)]
    for y in range(h):
        for x in range(w):
            a = at(g, x - 1, y - 1, w, h)
            b = at(g, x, y - 1, w, h)
            c = at(g, x + 1, y - 1, w, h)
            d = at(g, x - 1, y, w, h)
            e = at(g, x, y, w, h)
            f = at(g, x + 1, y, w, h)
            gg = at(g, x - 1, y + 1, w, h)
            hh = at(g, x, y + 1, w, h)
            ii = at(g, x + 1, y + 1, w, h)
            if b != hh and d != f:
                e0 = d if d == b else e
                e1 = b if (d == b and e != c) or (b == f and e != a) else e
                e2 = f if b == f else e
                e3 = d if (d == b and e != gg) or (d == hh and e != a) else e
                e4 = e
                e5 = f if (b == f and e != ii) or (hh == f and e != c) else e
                e6 = d if d == hh else e
                e7 = hh if (d == hh and e != ii) or (hh == f and e != gg) else e
                e8 = f if hh == f else e
            else:
                e0 = e1 = e2 = e3 = e4 = e5 = e6 = e7 = e8 = e
            out[3 * y][3 * x] = e0
            out[3 * y][3 * x + 1] = e1
            out[3 * y][3 * x + 2] = e2
            out[3 * y + 1][3 * x] = e3
            out[3 * y + 1][3 * x + 1] = e4
            out[3 * y + 1][3 * x + 2] = e5
            out[3 * y + 2][3 * x] = e6
            out[3 * y + 2][3 * x + 1] = e7
            out[3 * y + 2][3 * x + 2] = e8
    return out


def pack_rows(grid, w, h):
    wb = (w + 7) // 8
    out = []
    for y in range(h):
        for k in range(wb):
            b = 0
            for i in range(8):
                x = k * 8 + i
                if x < w and grid[y][x]:
                    b |= 0x80 >> i
            out.append(b)
    return out


def format_font_c(w, h, glyphs, k):
    sw, sh = w * k, h * k
    wb = (sw + 7) // 8
    nbytes = sh * wb
    lines = [
        "/*",
        f" * bm console font {sw}x{sh}, scaled {k}x from font{w}x{h} (Terminus Font,",
        " * (c) Dimitar Toshkov Zhekov, SIL Open Font License 1.1, see docs/LICENSE.font).",
        " * Generated by scripts/font_scale.py - do not edit.",
        f" * Glyphs are in code page 437 order; {wb} bytes per row, MSB = left.",
        " */",
        '#include "font.h"',
        "",
        f"static const uint8_t glyphs[256][{nbytes}] = {{",
    ]
    fn = scale2x if k == 2 else scale3x
    for code, g in enumerate(glyphs):
        sg = fn(g, w, h)
        raw = pack_rows(sg, sw, sh)
        ch = bytes([code]).decode("cp437")
        label = ch if 0x20 <= code < 0x7F and ch not in "\\*/" else f"0x{code:02x}"
        body = ", ".join(f"0x{b:02x}" for b in raw)
        lines.append(f"    {{ {body} }}, /* {label} */")
    lines += [
        "};",
        "",
        f"const font_t font_console_{sw}x{sh} = {{",
        f"    .width = {sw}, .height = {sh}, .glyphs = &glyphs[0][0],",
        "};",
        "",
    ]
    return "\n".join(lines)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    if len(sys.argv) == 1:
        src = os.path.join(root, "src", "gfx", "font8x16.c")
        w, h, glyphs = parse_font_c(src)
        for k in (2, 3):
            dst = os.path.join(root, "src", "gfx", f"font{w * k}x{h * k}.c")
            with open(dst, "w", encoding="utf-8", newline="\n") as f:
                f.write(format_font_c(w, h, glyphs, k))
        return
    if len(sys.argv) != 3 or sys.argv[2] not in ("2", "3"):
        raise SystemExit("usage: font_scale.py [src/gfx/font8x16.c 2|3]")
    w, h, glyphs = parse_font_c(sys.argv[1])
    sys.stdout.write(format_font_c(w, h, glyphs, int(sys.argv[2])))


if __name__ == "__main__":
    main()
