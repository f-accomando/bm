#!/usr/bin/env python3
"""mklint.py - makes src/bm/lint_table.h, the C form of docs/spec/lint-rules.toml (the build lint).

  python scripts/mklint.py            write src/bm/lint_table.h
  python scripts/mklint.py --check    exit 1 if the file is not what the toml gives, or a rule names
                                      an API that is not in src/ai/api.tsv (make test-lint does this)

The toml is the source of truth. scripts/mkbm.py reads it (rules, python_checks); the SDK export bm_build_b16
uses the C table (src/bm/lint.c). Standard library only (Python 3.11+, tomllib)."""
import argparse
import os
import re
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RULES = os.path.join(ROOT, "docs", "spec", "lint-rules.toml")
API = os.path.join(ROOT, "src", "ai", "api.tsv")
OUT = os.path.join(ROOT, "src", "bm", "lint_table.h")
KINDS = ("call", "call_prefix", "word", "dotted")
C_KIND = {"call": "BM_LINT_CALL", "call_prefix": "BM_LINT_PREFIX", "word": "BM_LINT_WORD", "dotted": "BM_LINT_DOTTED"}


def load_rules(target="b16", path=RULES):
    """the rules of a target, in file order: [{kind, name, api, msg}]. SystemExit on a bad rule"""
    with open(path, "rb") as f:
        raw = tomllib.load(f)
    out = []
    for i, r in enumerate(raw.get("rule", [])):
        for key in ("target", "kind", "name", "api", "msg"):
            if key not in r:
                raise SystemExit(f"{path}: rule {i + 1}: missing key {key}")
        if r["kind"] not in KINDS:
            raise SystemExit(f"{path}: rule {i + 1}: kind {r['kind']!r} is not one of {', '.join(KINDS)}")
        if not isinstance(r["api"], bool):
            raise SystemExit(f"{path}: rule {i + 1}: api is true or false")
        if len(r["msg"]) > 79:
            raise SystemExit(f"{path}: rule {i + 1}: msg is at most 79 characters")
        if r["target"] == target:
            out.append(r)
    return out


def python_checks(target="b16"):
    """[(regex, msg)] for scripts/mkbm.py: the same rules as the C table"""
    out = []
    for r in load_rules(target):
        n = re.escape(r["name"])
        rx = {"call": rf"(?<![\w.:]){n}\(",
              "call_prefix": rf"(?<![\w.:]){n}\w+\(",
              "word": rf"(?<![\w.:]){n}(?![\w])",
              "dotted": rf"(?<![\w]){n}"}[r["kind"]]
        out.append((rx, r["msg"]))
    return out


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(target="b16"):
    L = ["/* GENERATED by scripts/mklint.py from docs/spec/lint-rules.toml. Do not edit: change the toml, run the script.",
         " * Included by src/bm/lint.c only. The rules of the .b16 build lint, in file order. */", "",
         "static const bm_lint_rule_t bm_lint_b16_rules[] = {"]
    for r in load_rules(target):
        L.append(f"    {{ {C_KIND[r['kind']]}, {c_str(r['name'])}, {c_str(r['msg'])} }},")
    L.append("};")
    return "\n".join(L) + "\n"


def api_names():
    names = set()
    with open(API, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            names.add(line.split("\t", 1)[0])
    return names


def api_problems():
    """rules whose name is not in src/ai/api.tsv although the toml says it is"""
    names = api_names()
    bad = []
    for r in load_rules():
        if not r["api"]:
            continue
        ok = any(n.startswith(r["name"]) for n in names) if r["kind"] == "call_prefix" else r["name"] in names
        if not ok:
            bad.append(r["name"])
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = generate()
    if a.check:
        bad = api_problems()
        if bad:
            print(f"mklint: not in src/ai/api.tsv: {', '.join(bad)} (set api = false or fix the name)", file=sys.stderr)
            return 1
        try:
            with open(OUT, encoding="utf-8", newline="") as f:
                have = f.read()
        except OSError:
            have = ""
        if have.replace("\r\n", "\n") != text:
            print("mklint: src/bm/lint_table.h is old: run python scripts/mklint.py", file=sys.stderr)
            return 1
        print("mklint: ok")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"mklint: wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
