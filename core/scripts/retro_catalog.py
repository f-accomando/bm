#!/usr/bin/env python3
"""Import NES/SNES game catalogs (PigSaint/GameDataBase CSV) into bm's INT8 genres.

Usage:
  python3 core/scripts/retro_catalog.py --fetch --lua-out build/train_retro.lua
  python3 core/scripts/retro_catalog.py nes.csv snes.csv --lua-out /sd/bm/train_retro.lua --max-per-genre 60
"""
import argparse
import collections
import csv
import os
import re
import urllib.request

DEFAULT_URLS = [
    "https://raw.githubusercontent.com/PigSaint/GameDataBase/main/console_nintendo_famicom_nes.csv",
    "https://raw.githubusercontent.com/PigSaint/GameDataBase/main/console_nintendo_superfamicom_snes.csv",
]

# Maps PigSaint/GameDataBase #genre:... tags (most specific first) to bm KB genre.* IDs.
GENRE_RULES = [
    ("puzzle>drop", "genre.match_puzzle"),
    ("puzzle>match", "genre.match_puzzle"),
    ("puzzle", "genre.logic_puzzle"),
    ("rpg>tactical", "genre.tactical_rpg"),
    ("sim>strategy>tactical", "genre.tactical_rpg"),
    ("rpg>dungeoncrawler", "genre.dungeon_crawler"),
    ("rpg>a", "genre.action_rpg"),
    ("action>hackandslash", "genre.action_rpg"),
    ("action:adventure", "genre.action_rpg"),
    ("rpg>j", "genre.turn_rpg"),
    ("rpg", "genre.turn_rpg"),
    ("brawler", "genre.beatemup"),
    ("fighting", "genre.fighting"),
    ("parlor>pinball", "genre.pinball"),
    ("racing", "genre.racing"),
    ("sports", "genre.sports"),
    ("action>platformer", "genre.platformer"),
    ("shmup", "genre.shmup"),
    ("shooting", "genre.shmup"),
    ("action>runandgun", "genre.shmup"),
    ("action>maze", "genre.maze_chase"),
    ("action>stealth", "genre.stealth"),
    ("stealth", "genre.stealth"),
    ("adventure", "genre.adventure"),
    ("sim>strategy", "genre.strategy"),
    ("strategy", "genre.strategy"),
    ("sim>", "genre.simulation"),
    ("board>party", "genre.multiplayer_party"),
    ("minigames", "genre.multiplayer_party"),
    ("music", "genre.rhythm_music"),
    ("rhythm", "genre.rhythm_music"),
    ("survival", "genre.survival"),
]


def map_genre(tags):
    if not tags or "#genre:notagame" in tags:
        return None
    for tag in re.findall(r"#genre:([^\s]+)", tags):
        low = tag.lower()
        for pat, gid in GENRE_RULES:
            if pat in low:
                return gid
    return None


def clean_title(raw):
    # Strip trailing parentheticals or non-ASCII Japanese tails when an ASCII prefix exists.
    s = raw.strip()
    s = re.sub(r"\s*\([^)]*\)\s*$", "", s)
    ascii_only = "".join(ch if 32 <= ord(ch) < 127 else " " for ch in s)
    ascii_only = " ".join(ascii_only.split())
    return ascii_only if len(ascii_only) >= 3 else ""


def load_rows(sources):
    by_genre = collections.defaultdict(list)
    seen_ids = set()
    for src in sources:
        if src.startswith("http://") or src.startswith("https://"):
            with urllib.request.urlopen(src, timeout=30) as resp:
                lines = [ln.decode("utf-8", "replace") for ln in resp]
        else:
            with open(src, "r", encoding="utf-8", errors="replace") as f:
                lines = f.readlines()
        for row in csv.DictReader(lines):
            gid = map_genre(row.get("Tags", ""))
            if not gid:
                continue
            uid = (row.get("ID") or "").strip()
            if uid and uid in seen_ids:
                continue
            title = clean_title(row.get("Title", ""))
            if not title:
                continue
            if uid:
                seen_ids.add(uid)
            by_genre[gid].append(title)
    return by_genre


def write_lua_trainer(by_genre, out_path, max_per_genre, steps, save_path):
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    total = 0
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("-- Auto-generated by core/scripts/retro_catalog.py\n")
        f.write("-- Trains bm's INT8 head on NES/SNES titles and saves BMAI.\n\n")
        f.write("local pairs = {\n")
        for gid in sorted(by_genre):
            for title in by_genre[gid][:max_per_genre]:
                safe = title.replace("\\", "\\\\").replace('"', '\\"')
                f.write(f'  {{ "gioco stile {safe}", "{gid}" }},\n')
                total += 1
        f.write("}\n\n")
        f.write("local ok_n = 0\n")
        f.write("for i = 1, #pairs do\n")
        f.write(f"  if ai.learn(pairs[i][1], pairs[i][2], {steps}) then ok_n = ok_n + 1 end\n")
        f.write("end\n")
        f.write(f'assert(ai.save("{save_path}"), "ai.save failed")\n')
        f.write('print("retro_catalog: learned " .. ok_n .. "/" .. #pairs .. " titles -> ' + save_path + '")\n')
    return total


def main():
    ap = argparse.ArgumentParser(description="Import NES/SNES CSVs into bm genre training scripts.")
    ap.add_argument("inputs", nargs="*", help="Local CSV paths or URLs")
    ap.add_argument("--fetch", action="store_true", help="Fetch NES & SNES CSVs from PigSaint/GameDataBase")
    ap.add_argument("--lua-out", help="Write Lua ai.learn/ai.save script to this path")
    ap.add_argument("--save-path", default="/bm/assist.bin", help="Target BMAI path for ai.save()")
    ap.add_argument("--max-per-genre", type=int, default=40, help="Max titles per genre (default: 40)")
    ap.add_argument("--steps", type=int, default=4, help="ai.learn steps per title (default: 4)")
    args = ap.parse_args()

    sources = list(args.inputs)
    if args.fetch:
        sources.extend(DEFAULT_URLS)
    if not sources:
        ap.error("provide CSV paths or --fetch")

    by_genre = load_rows(sources)
    for gid in sorted(by_genre):
        print(f"{gid:24s} {len(by_genre[gid]):4d} titles")
    if args.lua_out:
        n = write_lua_trainer(by_genre, args.lua_out, args.max_per_genre, args.steps, args.save_path)
        print(f"Wrote {n} training pairs to {args.lua_out}")


if __name__ == "__main__":
    main()
