static uint8_t rows_of(const char *s)
{
    uint8_t b = 0;
    for (int i = 0; s[i]; i++)
        if (s[i] == '#')
            b |= (uint8_t)(1u << i);
    return b;
}

int n8_glyph(int c, uint8_t rows[5])
{
    const char *const *g;
    int w;
    c &= 255;
    if (c >= 16 && c < 128) {
        g = narrow[c - 16];
        w = 3;
    } else if (c >= 128 && c < 154) {
        g = wide[c - 128];
        w = 7;
    } else if (c >= 254) {
        g = arc[c - 254];
        w = 7;
    } else if (c >= 154) {
        g = kana;
        w = 7;
    } else {
        memset(rows, 0, 5);
        return 0;
    }
    for (int i = 0; i < 5; i++)
        rows[i] = rows_of(g[i]);
    return w;
}
