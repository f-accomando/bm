static const char mul[] =
    "; __a * __b -> __a (the low 16 bits)\n"
    "__mul:\n"
    "    lda #0\n"
    "    sta __r\n"
    "    sta __r+1\n"
    "    ldx #16\n"
    "@bit:\n"
    "    lsr __b+1\n"
    "    ror __b\n"
    "    bcc @skip\n"
    "    clc\n"
    "    lda __r\n"
    "    adc __a\n"
    "    sta __r\n"
    "    lda __r+1\n"
    "    adc __a+1\n"
    "    sta __r+1\n"
    "@skip:\n"
    "    asl __a\n"
    "    rol __a+1\n"
    "    dex\n"
    "    bne @bit\n"
    "    lda __r\n"
    "    sta __a\n"
    "    lda __r+1\n"
    "    sta __a+1\n"
    "    rts\n";

static const char udiv[] =
    "; __a / __b -> __a, the rest in __r (by 0: $FFFF)\n"
    "__udiv:\n"
    "    lda #0\n"
    "    sta __r\n"
    "    sta __r+1\n"
    "    ldx #16\n"
    "@bit:\n"
    "    asl __a\n"
    "    rol __a+1\n"
    "    rol __r\n"
    "    rol __r+1\n"
    "    bcs @over\n"
    "    lda __r\n"
    "    sec\n"
    "    sbc __b\n"
    "    tay\n"
    "    lda __r+1\n"
    "    sbc __b+1\n"
    "    bcc @next\n"
    "    jmp @take\n"
    "@over:\n"
    "    lda __r\n"
    "    sec\n"
    "    sbc __b\n"
    "    tay\n"
    "    lda __r+1\n"
    "    sbc __b+1\n"
    "@take:\n"
    "    sta __r+1\n"
    "    sty __r\n"
    "    inc __a\n"
    "@next:\n"
    "    dex\n"
    "    bne @bit\n"
    "    rts\n";

