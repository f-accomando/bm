static const char rnd[] =
    "; random(): a byte from a 16-bit shift register\n"
    "__random:\n"
    "    ldx #8\n"
    "@bit:\n"
    "    lsr __rnd+1\n"
    "    ror __rnd\n"
    "    bcc @skip\n"
    "    lda __rnd+1\n"
    "    eor #$B4\n"
    "    sta __rnd+1\n"
    "@skip:\n"
    "    dex\n"
    "    bne @bit\n"
    "    lda __rnd\n"
    "    eor __frame\n"
    "    rts\n";

const char *cc_runtime_head(void) { return head; }

const char *cc_runtime_part(int part)
{
    switch (part) {
    case RT_BASE: return base;
    case RT_MUL: return mul;
    case RT_UDIV: return udiv;
    case RT_SDIV: return sdiv;
    case RT_SHIFT: return shift;
    case RT_SPRITE: return sprite;
    case RT_PALETTE: return palette;
    case RT_RANDOM: return rnd;
    default: return "";
    }
}
