    "    sta __sign\n"
    "    lda __a+1\n"
    "    bpl @a\n"
    "    jsr __neg_a\n"
    "@a:\n"
    "    lda __b+1\n"
    "    bpl @b\n"
    "    sec\n"
    "    lda #0\n"
    "    sbc __b\n"
    "    sta __b\n"
    "    lda #0\n"
    "    sbc __b+1\n"
    "    sta __b+1\n"
    "@b:\n"
    "    jsr __udiv\n"
    "    lda __sign\n"
    "    bpl @q\n"
    "    jsr __neg_a\n"
    "@q:\n"
    "    lda __sign+1\n"
    "    bpl @r\n"
    "    sec\n"
    "    lda #0\n"
    "    sbc __r\n"
    "    sta __r\n"
    "    lda #0\n"
    "    sbc __r+1\n"
    "    sta __r+1\n"
    "@r:\n"
    "    rts\n"
    "__neg_a:\n"
    "    sec\n"
    "    lda #0\n"
    "    sbc __a\n"
    "    sta __a\n"
    "    lda #0\n"
    "    sbc __a+1\n"
    "    sta __a+1\n"
    "    rts\n";

