const char *cc_runtime_head(int snes) { return snes ? snes_head : head; }

const char *cc_runtime_part(int snes, int part)
{
    switch (part) {
    case RT_BASE: return snes ? snes_base : base;
    case RT_MUL: return mul;
    case RT_UDIV: return udiv;
    case RT_SDIV: return sdiv;
    case RT_SHIFT: return shift;
    case RT_SPRITE: return snes ? snes_sprite : sprite;
    case RT_PALETTE: return snes ? snes_palette : palette;
    case RT_RANDOM: return rnd;
    default: return "";
    }
}
