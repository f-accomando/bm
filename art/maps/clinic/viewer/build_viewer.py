#!/usr/bin/env python3
"""build_viewer.py: a small cart that draws clinic.bmk in 3D, to look at the kit on the PC (bmhost).

  python3 build_viewer.py KIT.bmk OUT_DIR [--look texture|flat] [--light day|dusk]
  OUT_DIR/viewer.bm is made; then
  build/host/bmhost-bin OUT_DIR/viewer.bm --shots OUT_DIR/shots --every 12 --from 4 --seconds N --quiet

Each view of VIEWS lasts 12 frames. Not a game: no input, no collision.
"""
import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
sys.path.insert(0, os.path.join(HERE, ".."))
import build_clinic as B  # noqa: E402

# (name, eye x, y, z, target x, y, z)
VIEWS = [
    ("overview", 38, 58, 50, 38, 0, 22),
    ("wardA", 8.5, 9, 18, 8.5, 1.2, 8),
    ("wardA_in", 11, 4.2, 12, 6, 3.4, 6),
    ("hall", 15, 5.2, 9.5, 28, 2, 9.5),
    ("hall_stair", 20, 5.2, 9.5, 34, 0.5, 9.5),
    ("wardC", 15, 7, 21, 19, 3, 15),
    ("atrium", 33, 5, 12, 40, 1, 8),
    ("yard", 44, 6.5, 19, 52, 0.5, 11),
    ("yard2", 57, 7, 8, 48, 0.5, 17),
    ("alley", 47.5, 5, 29, 47.5, 0.5, 42),
    ("gate", 60, 5.2, 10.5, 72, 2.5, 10.5),
    ("street", 52, 3, 24, 52, 1.2, 12),
]

LUA = '''-- viewer of clinic.bmk (generated by build_viewer.py)
local MODELS = {
%MODELS%
}
local VIEWS = {
%VIEWS%
}
local SKY = %SKY%
local world
local objs = {}
local frame = 0

local function look(x, y, z, tx, ty, tz)
  local dx, dy, dz = tx - x, ty - y, tz - z
  return math.atan(dx, dz), math.atan(dy, math.sqrt(dx * dx + dz * dz))
end

function _init()
  world = map3d_build({ floor = "floor", height = "height", walls = "walls", cell = 1.0, step = 0.25 })
  for _, k in pairs(MODELS) do k.mesh = model(k.name) end
  local mw, mh = msize()
  for cz = 0, mh - 1, 2 do
    for cx = 0, mw - 1, 2 do
      local k = MODELS[mget(cx, cz, "objects")]
      if k and k.mesh then
        local x, z = cx / 2 + 0.5, cz / 2 + 0.5
        objs[#objs + 1] = { m = k.mesh, x = x, z = z, y = map3d_height(world, x, z) or 0 }
      end
    end
  end
  log("viewer: " .. #objs .. " objects")
end

function _update() frame = frame + 1 end

function _draw()
  local v = VIEWS[(frame // 12) % #VIEWS + 1]
  cls(SKY)
  zclear()
  local yaw, pitch = look(v[2], v[3], v[4], v[5], v[6], v[7])
  camera3d(v[2], v[3], v[4], yaw, pitch, %FOV%)
  %LIGHT%
  fog3d(SKY, %FOGN%, %FOGF%)
  map3d_draw(world, 0)
  for _, o in ipairs(objs) do draw3d(o.m, o.x, o.y, o.z, 0, 0, 0, 1, 0) end
end
'''

LIGHTS = {
    "day": ("light3d(-0.45, 0.8, -0.35, 0.55)", "0x9AA3B5", 30, 90),
    "dusk": ("light3d(-0.4, 0.7, -0.5, 0.42)", "0x5E6680", 22, 70),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("kit")
    ap.add_argument("out")
    ap.add_argument("--look", choices=("texture", "flat"), default="texture")
    ap.add_argument("--light", choices=sorted(LIGHTS), default="dusk")
    ap.add_argument("--fov", type=int, default=60)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    suffix = "_f" if a.look == "flat" else ""
    models = "\n".join('  [%d] = { name = "%s%s" },' % (B.IDS[n], n, suffix) for n, *_ in B.OBJECTS)
    views = "\n".join("  { %s, %g, %g, %g, %g, %g, %g }," % ((repr(v[0]),) + tuple(v[1:])) for v in VIEWS)
    light, sky, fn, ff = LIGHTS[a.light]
    lua = (LUA.replace("%MODELS%", models).replace("%VIEWS%", views).replace("%SKY%", sky).replace("%FOV%", str(a.fov))
           .replace("%LIGHT%", light).replace("%FOGN%", str(fn)).replace("%FOGF%", str(ff)))
    lua_path = os.path.join(a.out, "main.lua")
    open(lua_path, "w").write(lua)
    cart = os.path.join(a.out, "viewer.bm")
    subprocess.check_call([sys.executable, os.path.join(ROOT, "scripts", "mkbm.py"), "-o", cart, "--lua", lua_path,
                           "--res", "640x360", "--title", "clinic viewer"])
    subprocess.check_call([sys.executable, os.path.join(ROOT, "scripts", "bmres.py"), "add", cart, a.kit, "-o", cart])
    print("wrote", cart, "views:", ", ".join(v[0] for v in VIEWS))


if __name__ == "__main__":
    main()
